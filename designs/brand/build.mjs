// Rebuild the shared UI lockup, standalone logos, and browser/touch icons.
// Source artwork is SVG; Playwright rasterizes it without a runtime dependency.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const publicDir = path.join(root, 'public');
const source = JSON.parse(await fs.readFile(path.join(here, 'source.json'), 'utf8'));
const mark = await fs.readFile(path.join(root, source.markSource), 'utf8');
const wordmark = await fs.readFile(path.join(root, source.wordmarkSource), 'utf8');
const body = svg => svg.replace(/^.*?<svg\b[^>]*>/s, '').replace(/<\/svg>\s*$/, '');
const markBody = body(mark);
const wordBody = body(wordmark);
const wordViewBox = wordmark.match(/viewBox="([^"]+)"/)[1];
const wordWidth = Number(wordViewBox.split(' ')[2]);
const width = Math.ceil(42 + wordWidth);
const darkMark = markBody.replaceAll(source.palette.primary, source.palette.darkPrimary).replaceAll(source.palette.signal, source.palette.darkSignal);
const wrapper = (w, h, inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" fill="none" role="img" aria-label="ScanHub">${inner}</svg>\n`;
const logo = (dark = false) => wrapper(width, 40, `<g transform="translate(0 4)">${dark ? darkMark : markBody}</g><g class="wordmark" transform="translate(42 10)" fill="${dark ? '#ededed' : '#101936'}">${wordBody}</g>`);
await fs.writeFile(path.join(publicDir, 'logo.svg'), logo());
await fs.writeFile(path.join(publicDir, 'logo-dark.svg'), logo(true));
const themeStyle = `<style>@media(prefers-color-scheme:dark){.merge-primary{fill:${source.palette.darkPrimary}}.merge-signal{fill:${source.palette.darkSignal}}}</style>`;
await fs.writeFile(path.join(publicDir, 'favicon.svg'), wrapper(32, 32, themeStyle + markBody));
const uiMark = `<svg class="brand-mark" viewBox="0 0 32 32" fill="none" aria-hidden="true" focusable="false">${markBody}</svg>`;
const uiWord = `<svg class="brand-wordmark" viewBox="${wordViewBox}" fill="currentColor" aria-hidden="true" focusable="false">${wordBody}</svg>`;
const lockup = `<span class="brand-lockup" role="img" aria-label="ScanHub">${uiMark}<span class="brand-name">${uiWord}</span></span>`;
await fs.writeFile(path.join(publicDir, 'brand.js'), `// ScanHub Merge identity; generated by node designs/brand/build.mjs.\nwindow.ScanHubBrand = Object.freeze(${JSON.stringify({ mark: uiMark, logo: lockup }, null, 2)});\n`);

const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  async function raster(svg, w, h) {
    await page.setViewportSize({ width: w, height: h });
    await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block;width:100%;height:100%}</style>${svg}`);
    return page.screenshot({ omitBackground: true });
  }
  await fs.writeFile(path.join(publicDir, 'logo.png'), await raster(logo(), width * 4, 160));
  await fs.writeFile(path.join(publicDir, 'logo-dark.png'), await raster(logo(true), width * 4, 160));
  const icons = [];
  for (const size of [16, 32, 48]) icons.push({ size, png: await raster(mark, size, size) });
  const header = Buffer.alloc(6 + icons.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(icons.length, 4);
  let offset = header.length;
  icons.forEach(({ size, png }, i) => {
    const at = 6 + i * 16;
    header[at] = header[at + 1] = size;
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(png.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += png.length;
  });
  await fs.writeFile(path.join(publicDir, 'favicon.ico'), Buffer.concat([header, ...icons.map(x => x.png)]));
  const touch = wrapper(180, 180, `<rect width="180" height="180" rx="36" fill="#fff"/><g transform="translate(18 18) scale(4.5)">${markBody}</g>`);
  await fs.writeFile(path.join(publicDir, 'apple-touch-icon.png'), await raster(touch, 180, 180));
  await page.setViewportSize({ width: 1000, height: 440 });
  await page.setContent(`<style>*{box-sizing:border-box}body{margin:0;font:14px system-ui;color:#525252}.row{height:220px;padding:48px;display:flex;align-items:center;justify-content:space-between}.dark{background:#141415;color:#a1a1a6}.row svg{width:${width * 1.8}px;height:72px}.sizes{display:flex;align-items:center;gap:20px}.sizes svg{width:var(--s);height:var(--s)}small{display:block;margin-bottom:16px}</style><div class="row"><div><small>04 / Merge · Light</small>${logo()}</div><div class="sizes">${[16,24,32,48].map(s => mark.replace('<svg ', `<svg style="--s:${s}px" `)).join('')}</div></div><div class="row dark"><div><small>04 / Merge · Dark</small>${logo(true)}</div><div class="sizes">${[16,24,32,48].map(s => wrapper(32,32,darkMark).replace('<svg ', `<svg style="--s:${s}px" `)).join('')}</div></div>`);
  await page.screenshot({ path: path.join(here, 'logo-preview.png') });
} finally {
  await browser.close();
}
console.log(`Rebuilt ${source.name} logos, favicon (16/32/48), touch icon, and preview.`);
